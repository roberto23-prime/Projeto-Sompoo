def calcular_probabilidade_roubo(
    tipo_carga_input,
    peso_carga,
    caminhao_roubado_input,
    ano,
    estado_input,
    cidade_input,
    estrada_input,
    rodovia_input,
    latitude=-23.55,
    longitude=-46.63
):
    """
    Calculadora profissional de probabilidade de roubo de carga.
    """
    try:
        # Codificar variáveis (nomes → números para o modelo)
        tipo_carga_encoded = label_encoders['Tipo de Carga'].transform([str(tipo_carga_input)])[0]
        caminhao_roubado_encoded = label_encoders['Caminhão Roubado'].transform([str(caminhao_roubado_input)])[0]
        estado_encoded = label_encoders['Estado'].transform([str(estado_input)])[0]
        cidade_encoded = label_encoders['Cidade'].transform([str(cidade_input)])[0]
        estrada_encoded = label_encoders['Estrada'].transform([str(estrada_input)])[0]
        rodovia_encoded = label_encoders['Rodovia'].transform([str(rodovia_input)])[0]

        # Criar dados numéricos para o modelo
        novo_dado = pd.DataFrame({
            'Tipo de Carga': [tipo_carga_encoded],
            'Peso da Carga (kg)': [peso_carga],
            'Caminhão Roubado': [caminhao_roubado_encoded],
            'Ano': [ano],
            'Estado': [estado_encoded],
            'Cidade': [cidade_encoded],
            'Estrada': [estrada_encoded],
            'Rodovia': [rodovia_encoded],
            'Latitude': [latitude],
            'Longitude': [longitude]
        })

        # Usar o modelo treinado
        probabilidade = rf_model.predict_proba(novo_dado)[:, 1][0] * 100
        previsao_binaria = rf_model.predict(novo_dado)[0]

        print(f"DEBUG - Probabilidade calculada pelo modelo: {probabilidade:.2f}%")

        # Classificação de risco
        if probabilidade > 70:
            risco = "ALTO RISCO"
        elif probabilidade > 40:
            risco = "MEDIO RISCO"
        else:
            risco = "BAIXO RISCO"

        # Relatório formatado
        print("\n" + "="*80)
        print(f"ANÁLISE DE RISCO DE ROUBO DE CARGA - SOMPO SEGUROS")
        print("="*80)
        print(f"ROTA: {cidade_input.upper()} - {estado_input.upper()}")
        print(f"RODOVIA: {rodovia_input}")
        print(f"CARGA: {tipo_carga_input.upper()} ({peso_carga:,} kg)")
        print(f"CAMINHÃO: {'ROUBADO' if caminhao_roubado_input == 'Sim' else 'NORMAL'}")
        print(f"ANO DA OPERAÇÃO: {ano}")
        print(f"COORDENADAS: {latitude:.4f}°, {longitude:.4f}°")
        print("="*80)
        print(f"PROBABILIDADE DE ROUBO: {probabilidade:.2f}% ({risco})")
        print(f"PREVISÃO: {'ROUBO PROVÁVEL' if previsao_binaria == 1 else 'SEGURANÇA PROVÁVEL'}")
        print("="*80)

        # Recomendações específicas
        print("\nRECOMENDAÇÕES DE SEGURANÇA:")
        if probabilidade > 70:
            print("MEDIDAS OBRIGATÓRIAS:")
            print("   - Escolta armada POLICIAL obrigatória")
            print("   - Rastreamento GPS em tempo real 24/7")
            print("   - Seguro com cobertura TOTAL e franquia zero")
            print("   - Operação SÓ em horário diurno")
            print("   - Veículo blindado nível III-A")
            print("   - Comunicar PM e PRF antes da operação")
        elif probabilidade > 40:
            print("MEDIDAS RECOMENDADAS:")
            print("   - Escolta privada armada")
            print("   - Monitoramento GPS contínuo")
            print("   - Seguro reforçado com cobertura ampliada")
            print("   - Evitar horários entre 22h-6h")
            print("   - Verificar antecedentes da rota")
        else:
            print("PROCEDIMENTOS PADRÃO:")
            print("   - Monitoramento GPS básico")
            print("   - Seguro padrão da Sompo")
            print("   - Cumprir checklist operacional")
            print("   - Manter comunicação com base")

        print("="*80)
        print(f"ANÁLISE CONCLUÍDA - {risco}")
        return probabilidade

    except ValueError as e:
        print(f"ERRO DE VALIDAÇÃO: {str(e)}")
        print("Valores selecionados não existem no modelo. Use valores do dataset original.")
        return None
    except Exception as e:
        print(f"ERRO NO MODELO: {str(e)}")
        print("Verifique se rf_model e label_encoders estão carregados.")
        return None

