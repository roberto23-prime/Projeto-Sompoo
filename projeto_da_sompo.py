def analise_exploratoria_interativa(variavel='Estado'):
    """
    Análise exploratória interativa por variável categórica.
    """
    print(f"ANÁLISE EXPLORATÓRIA - {variavel.upper()}")
    print("="*50)

    # Porcentagem de roubo por variável
    if variavel in data.columns:
        theft_by_var = data.groupby(variavel)['Roubo de Carga'].value_counts(normalize=True).unstack() * 100
        theft_by_var = theft_by_var.fillna(0)

        if 'Sim' in theft_by_var.columns:
            print(f"\n% ROUBO DE CARGA por {variavel}:")
            porcentagens = theft_by_var['Sim'].sort_values(ascending=False)
            for idx, pct in porcentagens.items():
                print(f"   {idx}: {pct:.2f}%")

            # Gráfico
            plt.figure(figsize=(10, 6))
            porcentagens.plot(kind='barh', color='coral')
            plt.title(f'Porcentagem de Roubo de Carga por {variavel}')
            plt.xlabel('Porcentagem (%)')
            plt.ylabel(variavel)
            plt.tight_layout()
            plt.show()
        else:
            print("Nenhuma ocorrência de 'Sim' encontrada para esta variável.")

    print("\nESTATÍSTICAS GERAIS:")
    print(f"Total de sinistros: {len(data):,}")
    print(f"Roubos de carga: {(data['Roubo de Carga'] == 'Sim').sum():,}")
    print(f"Taxa geral de roubo: {((data['Roubo de Carga'] == 'Sim').mean() * 100):.2f}%")

# Interface para análise exploratória
print("SELECIONE A VARIÁVEL PARA ANÁLISE EXPLORATÓRIA:")
variaveis = ['Estado', 'Tipo de Carga', 'Caminhão Roubado', 'Rodovia']
